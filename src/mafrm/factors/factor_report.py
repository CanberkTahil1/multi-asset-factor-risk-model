        "correlation before the change was made, which is what made it cheap.",
        "",
        "**It is not a gate and must never become one.** A condition number is a property of "
        "the market in that window -- factors genuinely do co-move in a crisis -- not a "
        "property of the implementation, so there is no value of it that would mean this "
        "code is wrong.",
        "",
        f"![Condition number of the factor correlation matrix]({figure_name})",
        "",
        "| Window | Raw: median / max | Orthogonalized: median / max | Raw dates | Orth dates |",
        "|---|---|---|---|---|",
