"""Generates ``reports/factor_correlations.md``. SPEC.md 4.1.

SPEC.md 4.1 asks for one artefact from the macro factor set: "Report the pre- and
post-orthogonalization correlation matrices side by side." This writes them, plus
the three things a reader needs in order to know whether to believe them -- what
the eigendecomposition actually did, which pairs the orthogonalization was and
was not asked to touch, and how the pre-registered duration predictions of
``experiments.md`` rows 64-67 came out.

The report states failures in the same voice as successes. The W2-P1 acceptance
bar was "no factor pair exceeds 0.15 post-orthogonalization" and it is not met;
the table below says so, per pair, and the section that follows separates the
pairs SPEC.md 4.1 never orthogonalizes from the one it does and which got worse.
Neither the bar nor the registered prediction bands are adjusted here.

CLAUDE.md invariant 5: everything read stops strictly before
``sample.holdout_start``.
"""

