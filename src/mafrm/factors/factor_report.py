        "No correct implementation could have passed. And meeting it would have been "
        "**harmful**: SPEC.md 5.1 estimates a K-by-K factor correlation matrix at a "
        f"{cfg.model.covariance.factor_correlation_halflife.short}-day half-life and SPEC.md "
