def report_path() -> Path:
    """``reports/factor_correlations.md`` -- committed, per CLAUDE.md."""
    return Path(__file__).resolve().parents[3] / "reports" / "factor_correlations.md"


def figure_path() -> Path:
    """``reports/factor_condition_number.png`` -- committed, per CLAUDE.md."""
    return Path(__file__).resolve().parents[3] / "reports" / "factor_condition_number.png"


@dataclass(frozen=True)
class ReportInputs:
    """Everything the report renders, built once so the sections cannot disagree."""

    panel: macro.FactorPanel
    gates: tuple[macro.GateResult, ...]
    conditioning: macro.Conditioning
    durations: tuple[macro.DurationEstimate, ...]


def build(cfg: config.Config | None = None) -> ReportInputs:
    """The panel and every measurement drawn from it."""
    settings = cfg or config.load()
    panel = macro.macro_factor_panel(config=settings)
    return ReportInputs(
        panel=panel,
        gates=macro.gate_results(panel, config=settings),
        conditioning=macro.conditioning(panel, config=settings),
        durations=macro.duration_check(panel, config=settings),
    )


def _matrix(frame: pd.DataFrame) -> str:
    header = "| | " + " | ".join(frame.columns) + " |"
    rule = "|---" * (len(frame.columns) + 1) + "|"
    rows = [
        "| **" + str(name) + "** | " + " | ".join(f"{value:+.3f}" for value in row) + " |"
        for name, row in frame.iterrows()
    ]
    return "\n".join([header, rule, *rows])


def _pairs(frame: pd.DataFrame) -> list[tuple[str, str, float]]:
    """Off-diagonal correlations, each pair once, ordered by magnitude."""
    names = [str(name) for name in frame.columns]
    values = frame.to_numpy(dtype=float)
    pairs = [
        (left, names[other], float(values[position, other]))
        for position, left in enumerate(names)
        for other in range(position + 1, len(names))
    ]
    return sorted(pairs, key=lambda item: abs(item[2]), reverse=True)


