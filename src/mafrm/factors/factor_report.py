def draw(inputs: ReportInputs, cfg: config.Config) -> Figure:
    """The condition-number figure. SPEC.md 4.1.2.

    Two lines and the crisis windows shaded. The claim the figure makes is the
    one CLAUDE.md's second failure mode is about: the raw factor correlation
    matrix deteriorates in exactly the crises that matter, and the
    orthogonalization is what keeps the orthogonalized line flat through them.

    Drawn on a linear axis, not a log one. The interesting range is roughly 3 to
    18 and a log axis would compress precisely the crisis excursions the figure
    exists to show.
    """
    conditioning = inputs.conditioning
    figure, axis = plt.subplots(figsize=(11, 5))
    left_edge = conditioning.raw.index[0]

    for window in cfg.model.costs.spread_vs_volatility.crisis_windows:
        # `axvspan` is typed for floats only, so the ignores are a stub gap
        # rather than a cast -- the same note as in mafrm.costs.spread_report.
        axis.axvspan(
            pd.Timestamp(window.start),  # type: ignore[arg-type]
            pd.Timestamp(window.end),  # type: ignore[arg-type]
            color="0.85",
            zorder=0,
            linewidth=0,
        )
        # The GFC window opens before the series does -- credit needs its burn-in
        # -- so the label is clamped to the visible edge rather than clipped off.
        axis.annotate(
            window.label,
            xy=(max(pd.Timestamp(window.start), left_edge), 0.02),
            xycoords=("data", "axes fraction"),
            fontsize=8,
            color="0.35",
            ha="left",
            va="bottom",
        )

    axis.plot(
        conditioning.raw.index,
        conditioning.raw.to_numpy(),
        color="#b2182b",
        linewidth=1.4,
        label="raw factors",
        zorder=3,
    )
    axis.plot(
        conditioning.orthogonal.index,
        conditioning.orthogonal.to_numpy(),
        color="#2166ac",
        linewidth=1.4,
        label="after sequential orthogonalization",
        zorder=4,
    )

    axis.set_ylabel("condition number of the factor correlation matrix")
    axis.set_title(
        f"Conditioning of the 6-factor macro set, EWMA half-life "
        f"{conditioning.halflife}d -- reported, never gated",
        fontsize=11,
    )
    axis.legend(loc="upper left", frameon=False, fontsize=9)
    axis.grid(True, axis="y", color="0.9", linewidth=0.6)
    axis.set_axisbelow(True)
    for side in ("top", "right"):
        axis.spines[side].set_visible(False)
    axis.set_xlim(conditioning.raw.index[0], conditioning.raw.index[-1])
    axis.set_ylim(bottom=0.0)
    figure.text(
        0.5,
        -0.04,
        "Largest over smallest eigenvalue. A high value means the smallest eigenvalues of F "
        "are small, and small eigenvalues are the\nmost poorly estimated -- which is the bias "
        "SPEC.md 5.3's eigenfactor adjustment exists to correct, and why an optimizer "
        "loads onto them.",
        ha="center",
        fontsize=8,
        color="0.35",
    )
    return figure


def main() -> int:
    """``make report``: regenerate ``reports/factor_correlations.md``."""
    settings = config.load()
    inputs = build(settings)
    root = Path(__file__).resolve().parents[3]
    for path in (figure_path(), report_path()):
        path.parent.mkdir(parents=True, exist_ok=True)
    draw(inputs, settings).savefig(figure_path(), dpi=150, bbox_inches="tight")
    report_path().write_text(render(inputs, settings), encoding="utf-8")
    for path in (figure_path(), report_path()):
        print(f"wrote {path.relative_to(root)}")
    return 0


if __name__ == "__main__":  # pragma: no cover - entry point
    raise SystemExit(main())
