            "",
            "**The construction is not the suspect, and the other three rows are why.** A "
            "sign error, a units error or a reciprocal scale in the normalization would move "
            "all four instruments together; three of them land on their predictions. What "
            "row 67 measures is HY's *empirical* rates exposure rather than its analytical "
