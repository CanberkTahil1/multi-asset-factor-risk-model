        "there would mean PC1 and PC2 were swapping places and the two factors were "
        "changing meaning mid-sample.",
        "",
        f"Variance shares over the model window: level "
        f"{in_window[macro.LEVEL].min():.3f}-{in_window[macro.LEVEL].max():.3f}, slope "
        f"{in_window[macro.SLOPE].min():.3f}-{in_window[macro.SLOPE].max():.3f}. "
