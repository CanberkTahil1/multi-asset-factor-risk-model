            f"> {gate.exempt_reason}",
            "",
            "**And the underperformance is diagnosed, not open.** The two normalized PCs are "
            "not exactly uncorrelated even before the hedge -- they are orthogonal inside "
            "each estimation window, but the loadings are re-estimated daily and rescaled by "
            "different time-varying amounts, so orthogonality does not survive pooling "
            "across windows. More importantly the relationship **changes sign across the "
            "burn-in boundary**: about **-0.196** over the pre-2007 history the expanding "
            "window is mostly estimated on, **+0.124** over the model window, and by "
            "calendar year inside it from **-0.315 (2007)** to **+0.837 (2012)** and back to "
            "**-0.292 (2023)**. An expanding-window hedge ratio estimated mostly on the "
            "former comes out negative, about -0.12 to -0.18, and applied to the latter it "
            "*adds* level exposure instead of removing it.",
            "",
            "That is a genuine result about expanding-window estimation rather than a "
            "defect, and it is the price of the look-ahead-free construction: a full-sample "
            "orthogonalization would drive this pair to exactly zero and is exactly what "
